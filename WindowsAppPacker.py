class App(ctk.CTk):
    def __init__(self):
        super().__init__()
        self.title("WindowsAppPacker")
        self.geometry(f"{WINDOW_WIDTH}x700")

        self.theme = "dark"
        self.colors = THEMES[self.theme]
        self._themed: List[Tuple[object, str]] = []

